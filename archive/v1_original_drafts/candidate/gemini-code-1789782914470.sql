-- Demo 1: Basic Aggregation and Grouping
-- Goal: Count how many employees work in each department.
SELECT 
    department, 
    COUNT(employee_id) AS total_employees
FROM employees
GROUP BY department
ORDER BY total_employees DESC;

-- Demo 2: Group-Level Filtering with HAVING
-- Goal: Find the average salary per department, but only show departments 
-- where the average salary is strictly greater than $80,000.
SELECT 
    department, 
    AVG(salary) AS avg_salary
FROM employees
GROUP BY department
HAVING AVG(salary) > 80000;

-- Demo 3: The UNION Operator
-- Goal: Combine completely different datasets into a single result set 
-- for an "Archived Entities" report. Columns must align exactly.
SELECT 
    product_name AS entity_name, 
    'Discontinued Product' AS entity_type 
FROM products 
WHERE discontinued_date IS NOT NULL
UNION
SELECT 
    first_name || ' ' || last_name AS entity_name, 
    'Former Employee' AS entity_type 
FROM employees 
WHERE is_active = FALSE;


