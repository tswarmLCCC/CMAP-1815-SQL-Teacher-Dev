-- 1. Create a non-clustered index on the 'department' column in the employees table to speed up filtering.
CREATE INDEX idx_employees_department ON employees(department);

-- 2. The Final Query: Write a single query that utilizes a CTE and Joins to find 
-- the total revenue generated by each employee, including their location city.
-- Filter the final result to only show employees who generated more than $1000 in revenue.
WITH EmployeeRevenue AS (
    SELECT o.employee_id, SUM(ol.quantity * ol.unit_price) AS total_sales
    FROM orders o
    INNER JOIN order_lines ol ON o.order_id = ol.order_id
    GROUP BY o.employee_id
)
SELECT e.first_name, e.last_name, l.city, er.total_sales
FROM employees e
INNER JOIN EmployeeRevenue er ON e.employee_id = er.employee_id
INNER JOIN locations l ON e.location_id = l.location_id
WHERE er.total_sales > 1000
ORDER BY er.total_sales DESC;